def write_dictionary(tables: dict[str, pd.DataFrame], path: Path) -> None:
    lines = ["# Data dictionary (synthetic)", "",
             "Generated by `python -m datagen`. Every business, employee and revenue value is fictional. "
             "Region codes and province/regency statistics come from cahyadsn/wilayah (MIT, Kepmendagri 2025). "
             "Join key for geography: `desa_kode` / `geo_kode` (Kemendagri dotted code, e.g. `32.05.01.2001`).", ""]
    for name, df in tables.items():
        lines += [f"## `{name}` ({len(df):,} rows)", "", TABLE_NOTES.get(name, ""), "",
                  "| column | type | example |", "|---|---|---|"]
        sample = df.iloc[0] if len(df) else None
        for col, dtype in df.dtypes.items():
            ex = "" if sample is None else str(sample[col])[:40].replace("|", "/").replace("\n", " ")
            lines.append(f"| `{col}` | {dtype} | {ex} |")
        lines.append("")
    path.write_text("\n".join(lines))
